// Downloads every original puppy gallery asset (photos, videos and video posters)
// referenced by docs/reference/puppies-payload.json — plus the Happy Families photos listed in
// src/data/families.json — into public/media/.
// Usage from the project root: node scripts/fetch-media.mjs [https://puppy.instabizweb.com]
import { access, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

const ORIGIN = process.argv[2] ?? 'https://puppy.instabizweb.com'
const payloadPath = new URL('../docs/reference/puppies-payload.json', import.meta.url)
const puppies = JSON.parse(await readFile(payloadPath, 'utf8'))
const urls = new Set()

for (const puppy of puppies) {
  for (const media of puppy.media ?? []) {
    if (typeof media.url === 'string' && media.url.startsWith('/media/')) urls.add(media.url)
    if (typeof media.poster?.url === 'string' && media.poster.url.startsWith('/media/')) urls.add(media.poster.url)
  }
  if (typeof puppy.cover?.url === 'string' && puppy.cover.url.startsWith('/media/')) urls.add(puppy.cover.url)
}

// Happy Families wall (src/data/families.json is generated by scripts/extract-families.mjs).
try {
  const families = JSON.parse(await readFile(new URL('../src/data/families.json', import.meta.url), 'utf8'))
  for (const photo of families) if (typeof photo.url === 'string' && photo.url.startsWith('/media/')) urls.add(photo.url)
} catch {
  // families.json missing/empty: nothing to add.
}

console.log(`${urls.size} unique gallery assets from ${ORIGIN}`)
let ok = 0
let failed = 0

for (const url of urls) {
  const output = join('public', url)
  try {
    await access(output)
    ok += 1
    continue
  } catch {
    // Download missing local assets only.
  }

  try {
    const response = await fetch(new URL(url, ORIGIN))
    if (!response.ok) throw new Error(`HTTP ${response.status}`)
    await mkdir(dirname(output), { recursive: true })
    await writeFile(output, Buffer.from(await response.arrayBuffer()))
    ok += 1
    console.log(`  ✓ ${url}`)
  } catch (error) {
    failed += 1
    console.warn(`  ✗ ${url}: ${error instanceof Error ? error.message : String(error)}`)
  }
}

console.log(`done: ${ok}/${urls.size} available locally; ${failed} failed`)
if (failed > 0) process.exitCode = 1
